//! Rendering scraped help as a `.ezlo` file.

use super::{ScrapedHelp, ScrapedOpt};
use crate::spec::span::is_reserved_word;
use std::fmt::Write;

pub fn render_spec_file(cmd_name: &str, scraped: &ScrapedHelp) -> String {
    let mut out = String::new();
    out.push_str("# Auto-generated by `ezlo import` — review and move to ~/.config/ezlo/specs/ to customize.\n\n");
    push_cmd_header(&mut out, "", cmd_name, scraped.description.as_deref());
    for opt in &scraped.opts {
        push_opt_decl(&mut out, opt, 2);
    }

    for sub in &scraped.subcommands {
        let path = format!("{cmd_name} {}", sub.name);
        push_cmd_header(&mut out, "\n", &path, sub.description.as_deref());
        for opt in &sub.opts {
            push_opt_decl(&mut out, opt, 2);
        }
    }

    out
}

fn push_cmd_header(out: &mut String, lead: &str, path: &str, desc: Option<&str>) {
    // Writing to a `String` cannot fail.
    let _ = match desc.filter(|d| !d.is_empty()) {
        Some(desc) => writeln!(out, "{lead}cmd {path} \"{}\"", escape_spec_string(desc)),
        None => writeln!(out, "{lead}cmd {path}"),
    };
}

fn push_opt_decl(out: &mut String, opt: &ScrapedOpt, indent: usize) {
    let _ = write!(out, "{:indent$}opt {}", "", opt.flags.join(" "));
    if let Some(ph) = &opt.value_placeholder {
        let _ = write!(out, " <{}>", sanitize_ident(ph));
        if let Some(t) = infer_builtin_type(ph) {
            let _ = write!(out, " {t}");
        }
    }
    if let Some(d) = opt.description.as_deref().filter(|d| !d.is_empty()) {
        let _ = write!(out, " \"{}\"", escape_spec_string(d));
    }
    out.push('\n');
}

fn infer_builtin_type(placeholder: &str) -> Option<&'static str> {
    let lower = placeholder.to_ascii_lowercase();
    if lower.contains("dir") || lower.contains("folder") {
        Some("dir")
    } else if lower.contains("file") || lower.contains("config") {
        Some("file")
    } else if lower.contains("path") {
        Some("path")
    } else {
        None
    }
}

fn sanitize_ident(raw: &str) -> String {
    let mut s: String = raw
        .chars()
        .filter_map(|ch| match ch {
            '-' => Some('_'),
            c if c.is_ascii_alphanumeric() || c == '_' => Some(c.to_ascii_lowercase()),
            _ => None,
        })
        .collect();
    if !s.chars().next().is_some_and(|c| c.is_ascii_alphabetic() || c == '_') {
        s.insert(0, 'v');
    }
    if is_reserved_word(&s) {
        s.push_str("_val");
    }
    s
}

fn escape_spec_string(s: &str) -> String {
    s.replace('\\', "\\\\")
        .replace('"', "\\\"")
        .replace(['\n', '\t'], " ")
}
